function utf8Bytes(str: string): number[] {
  const bytes: number[] = [];
  for (let i = 0; i < str.length; i++) {
    let c = str.charCodeAt(i);
    if (c < 0x80) {
      bytes.push(c);
    } else if (c < 0x800) {
      bytes.push(0xc0 | (c >> 6), 0x80 | (c & 0x3f));
    } else if (c >= 0xd800 && c <= 0xdbff) {
      const c2 = str.charCodeAt(++i);
      const cp = 0x10000 + ((c & 0x3ff) << 10) + (c2 & 0x3ff);
      bytes.push(
        0xf0 | (cp >> 18),
        0x80 | ((cp >> 12) & 0x3f),
        0x80 | ((cp >> 6) & 0x3f),
        0x80 | (cp & 0x3f),
      );
    } else {
      bytes.push(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 0x3f), 0x80 | (c & 0x3f));
    }
  }
  return bytes;
}

const rotr = (x: number, n: number) => (x >>> n) | (x << (32 - n));
const hex8 = (x: number) => (x >>> 0).toString(16).padStart(8, "0");

function sha256FromBytes(bytes: number[]): string {
  const message = bytes.slice();
  const bitLen = message.length * 8;
  message.push(0x80);
  while (message.length % 64 !== 56) message.push(0);
  const hi = Math.floor(bitLen / 0x100000000);
  const lo = bitLen >>> 0;
  message.push((hi >>> 24) & 0xff, (hi >>> 16) & 0xff, (hi >>> 8) & 0xff, hi & 0xff);
  message.push((lo >>> 24) & 0xff, (lo >>> 16) & 0xff, (lo >>> 8) & 0xff, lo & 0xff);

  let h0 = 0x6a09e667, h1 = 0xbb67ae85, h2 = 0x3c6ef372, h3 = 0xa54ff53a;
  let h4 = 0x510e527f, h5 = 0x9b05688c, h6 = 0x1f83d9ab, h7 = 0x5be0cd19;
  const w = new Array<number>(64);

  for (let i = 0; i < message.length; i += 64) {
    for (let t = 0; t < 16; t++) {
      w[t] =
        (message[i + t * 4] << 24) |
        (message[i + t * 4 + 1] << 16) |
        (message[i + t * 4 + 2] << 8) |
        message[i + t * 4 + 3];
    }
    for (let t = 16; t < 64; t++) {
      const s0 = rotr(w[t - 15], 7) ^ rotr(w[t - 15], 18) ^ (w[t - 15] >>> 3);
      const s1 = rotr(w[t - 2], 17) ^ rotr(w[t - 2], 19) ^ (w[t - 2] >>> 10);
      w[t] = (w[t - 16] + s0 + w[t - 7] + s1) | 0;
    }
    let a = h0, b = h1, c = h2, d = h3, e = h4, f = h5, g = h6, h = h7;
    for (let t = 0; t < 64; t++) {
      const S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const temp1 = (h + S1 + ch + K[t] + w[t]) | 0;
      const S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const temp2 = (S0 + maj) | 0;
      h = g; g = f; f = e; e = (d + temp1) | 0;
      d = c; c = b; b = a; a = (temp1 + temp2) | 0;
    }
    h0 = (h0 + a) | 0; h1 = (h1 + b) | 0; h2 = (h2 + c) | 0; h3 = (h3 + d) | 0;
    h4 = (h4 + e) | 0; h5 = (h5 + f) | 0; h6 = (h6 + g) | 0; h7 = (h7 + h) | 0;
  }
  return [h0, h1, h2, h3, h4, h5, h6, h7].map(hex8).join("");
}

export function sha256hex(message: string): string {
  return sha256FromBytes(utf8Bytes(message));
}

export function parseHmacKeyHex(hex: string): number[] {
  if (!/^[0-9a-f]{64}$/i.test(hex)) throw new Error("chave HMAC inválida");
  const bytes: number[] = [];
  const normalized = hex.toLowerCase();
  for (let i = 0; i < normalized.length; i += 2) {
    bytes.push(Number.parseInt(normalized.slice(i, i + 2), 16));
  }
  return bytes;
}

export function hmacSha256hex(key: number[] | Uint8Array, message: string): string {
  const block = 64;
  let keyBytes = Array.from(key);
  if (keyBytes.length > block) keyBytes = parseHmacKeyHex(sha256FromBytes(keyBytes));
  while (keyBytes.length < block) keyBytes.push(0);
  const ipad = keyBytes.map((byte) => byte ^ 0x36);
  const opad = keyBytes.map((byte) => byte ^ 0x5c);
  const inner = parseHmacKeyHex(sha256FromBytes(ipad.concat(utf8Bytes(message))));
  return sha256FromBytes(opad.concat(inner));
}
